/**
 * Apply all translations for the given language.
 * @param {string} lang  'de' | 'en'
 */
function flipLangApply(lang) {
  var t = FLIPART86_I18N[lang];
  if (!t) return;

  /* 1. html[lang] attribute */
  document.documentElement.lang = lang;

  /* 2. localStorage */
  try { localStorage.setItem('flipart86_lang', lang); } catch(e) {}

  /* 3. Text translations via data-i18n */
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    var key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  /* 4. Aria-label translations via data-i18n-aria */
  document.querySelectorAll('[data-i18n-aria]').forEach(function(el) {
    var key = el.getAttribute('data-i18n-aria');
    if (t[key] !== undefined) {
      el.setAttribute('aria-label', t[key]);
    }
  });

  /* 5. Named elements with aria-labels (handled centrally) */
  var ariaMap = [
    ['impressum-modal',         t.imp_aria],
    ['lb-close',                t.lb_close],
    ['lb-prev',                 t.lb_prev],
    ['lb-next',                 t.lb_next],
    ['lightbox',                t.lb_aria],
  ];
  ariaMap.forEach(function(pair) {
    var el = document.getElementById(pair[0]);
    if (el && pair[1]) el.setAttribute('aria-label', pair[1]);
  });
  /* impressum close button (no id — target by selector) */
  var impClose = document.querySelector('#impressum-modal .imp-close');
  if (impClose) impClose.setAttribute('aria-label', t.lb_close || '');

  /* 6. Update switcher UI */
  var currentLabel = document.getElementById('lang-current');
  if (currentLabel) currentLabel.textContent = lang.toUpperCase();

  document.querySelectorAll('.lang-option').forEach(function(opt) {
    var isActive = opt.getAttribute('data-lang') === lang;
    opt.classList.toggle('active', isActive);
    opt.setAttribute('aria-selected', isActive ? 'true' : 'false');
  });

  /* 7. Expose current lang globally for JS modules (e.g. gallery) */
  window.FLIPART86_LANG = lang;
}

/**
 * Initialise: read localStorage → apply lang → wire up switcher UI.
 */
function flipLangInit() {
  var saved;
  try { saved = localStorage.getItem('flipart86_lang'); } catch(e) {}
  var lang = (saved === 'en') ? 'en' : 'de';

  flipLangApply(lang);
  _flipLangInitSwitcher();
}

/** Wire keyboard + click behaviour for the dropdown. */
function _flipLangInitSwitcher() {
  var btn      = document.getElementById('lang-btn');
  var dropdown = document.getElementById('lang-dropdown');
  if (!btn || !dropdown) return;

  function openDropdown() {
    dropdown.classList.add('open');
    btn.setAttribute('aria-expanded', 'true');
    /* focus first option */
    var first = dropdown.querySelector('.lang-option');
    if (first) first.focus();
  }
  function closeDropdown() {
    dropdown.classList.remove('open');
    btn.setAttribute('aria-expanded', 'false');
  }

  btn.addEventListener('click', function(e) {
    e.stopPropagation();
    if (dropdown.classList.contains('open')) { closeDropdown(); }
    else { openDropdown(); }
  });

  btn.addEventListener('keydown', function(e) {
    if (e.key === 'Enter' || e.key === ' ') {
      e.preventDefault();
      if (dropdown.classList.contains('open')) { closeDropdown(); }
      else { openDropdown(); }
    }
  });

  document.querySelectorAll('.lang-option').forEach(function(opt) {
    opt.addEventListener('click', function(e) {
      e.stopPropagation();
      flipLangApply(opt.getAttribute('data-lang'));
      closeDropdown();
      btn.focus();
    });
    opt.addEventListener('keydown', function(e) {
      if (e.key === 'Enter' || e.key === ' ') {
        e.preventDefault();
        opt.click();
      } else if (e.key === 'Escape') {
        closeDropdown();
        btn.focus();
      } else if (e.key === 'ArrowDown') {
        e.preventDefault();
        var next = opt.nextElementSibling;
        if (next) next.focus();
      } else if (e.key === 'ArrowUp') {
        e.preventDefault();
        var prev = opt.previousElementSibling;
        if (prev) prev.focus();
        else btn.focus();
      }
    });
  });

  /* Close on outside click */
  document.addEventListener('click', function() { closeDropdown(); });

  /* ESC closes from anywhere */
  document.addEventListener('keydown', function(e) {
    if (e.key === 'Escape' && dropdown.classList.contains('open')) {
      closeDropdown();
      btn.focus();
    }
  });
}

/* ── Auto-init on DOM ready ── */
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', flipLangInit);
} else {
  flipLangInit();
}
